"""
ACC Apex Engineer Pro - Base de Conocimiento de Pistas y Trazadas Óptimas (track_knowledge_base.py)
Base de datos local exhaustiva con las mejores trazadas, referencias visuales de frenada,
marchas recomendadas, técnicas de vértice y consejos de ingeniero para todos los circuitos de ACC.
100% local, sin latencia ni dependencia de APIs externas.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional


@dataclass
class CornerKnowledge:
    id: str  # ej: "T1", "T4-T5", "T11"
    name: str  # ej: "Variante del Rettifilo", "Eau Rouge / Raidillon"
    spline_start: float  # Posición normalizada donde comienza la frenada (0.0 a 1.0)
    spline_apex: float  # Posición del vértice (apex)
    spline_exit: float  # Fin de la curva y zona de aceleración completa
    anticipation_offset: float  # Anticipación previa (típicamente 0.02 a 0.04 en spline)
    gear: int  # Marcha recomendada en GT3
    target_apex_speed: float  # Velocidad de referencia en km/h
    braking_marker: str  # Referencia visual (ej: "Cartel de 150m", "Final del piano exterior")
    braking_type: str  # "hard" (100% umbral), "trail" (progresivo), "lift" (toque/levantar)
    anticipation_advice: str  # Mensaje anticipado conciso y amigable para el piloto
    apex_technique: str  # Técnica en el vértice
    exit_technique: str  # Técnica de salida y tracción
    coaching_tips: Dict[str, str] = field(default_factory=dict)


@dataclass
class TrackKnowledge:
    track_id: str
    display_name: str
    country: str
    length_m: int
    corners: List[CornerKnowledge]


